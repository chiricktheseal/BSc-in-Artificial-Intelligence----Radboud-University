if __name__ == "__main__":
    # 1. Создаём граф
    graph = generate_graph(4, 5, 1, seed=42)

    # 2. Создаём решатель
    solver = ConnectionistSolver(
        graph=graph,
        #lr=0.5,           # Медленнее учимся
        #decay=0.1,        # Сильнее забываем старое
        tolerance=1e-4,   # Более грубая сходимость
        max_steps=500     # Не больше 500 итераций
    )

    # 3. Запускаем!
    final_harmony = solver.solve()

    # 4. Получаем результаты
    if solver.has_converged:
        print(f"Сошлось за {solver.steps_taken} шагов")
        print(f"Финальная гармония: {solver.harmony}")
        
        # Можно посмотреть историю
        history = solver.history
        for step in range(len(history.H)):
            print(f"Шаг {step}: H = {history.H[step]:.4f}")
